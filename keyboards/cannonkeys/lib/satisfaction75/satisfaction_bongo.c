// Which sprite set a given state draws from.  The large screen has a single
// set, so "minimal" there only drops the text overlay.
#    ifdef SAT75_OLED_LARGE
#        define BONGO_IDLE_SET(min) bongo_idle
#        define BONGO_PREP_SET(min) bongo_idle // no dedicated prep art at this size
#        define BONGO_TAP_SET(min) bongo_tap
#    else
#        define BONGO_IDLE_SET(min) ((min) ? bongo_idle_minimal : bongo_idle)
#        define BONGO_PREP_SET(min) ((min) ? bongo_prep_minimal : bongo_prep)
#        define BONGO_TAP_SET(min) ((min) ? bongo_tap_minimal : bongo_tap)
#    endif

enum bongo_state { BONGO_IDLE, BONGO_PREP, BONGO_TAP };

static uint8_t      anim_state         = BONGO_IDLE;
static uint32_t     idle_timeout_timer = 0;
static uint32_t     anim_timer         = 0;
static uint8_t      current_idle_frame = 0;
static uint8_t      current_tap_frame  = 0;
static matrix_row_t prev_matrix[MATRIX_ROWS];

// True when any key went from up to down since the last call.  A bitmap over
// the matrix rows answers this in MATRIX_ROWS * sizeof(matrix_row_t) bytes;
// the previous implementation kept two 100 entry arrays of row/column pairs
// to do the same job, and silently mis-detected if the matrix ever grew past
// 100 keys.
static bool detect_new_keypress(void) {
    bool pressed = false;

    for (uint8_t row = 0; row < MATRIX_ROWS; row++) {
        matrix_row_t current = matrix_get_row(row);
        if (current & ~prev_matrix[row]) {
            pressed = true;
        }
        prev_matrix[row] = current;
    }

    return pressed;
}

static void eval_anim_state(void) {
    bool new_keypress = detect_new_keypress();

    switch (anim_state) {
        case BONGO_IDLE:
            if (new_keypress) {
                anim_state = BONGO_TAP;
            }
            break;

        case BONGO_PREP:
            if (new_keypress) {
                anim_state = BONGO_TAP;
            } else if (timer_elapsed32(idle_timeout_timer) >= BONGO_IDLE_TIMEOUT) {
                anim_state         = BONGO_IDLE;
                current_idle_frame = 0;
            }
            break;

        case BONGO_TAP:
            // Tap lasts a single frame per keypress; between keystrokes the cat
            // hovers in prep until the idle timeout expires.
            if (!new_keypress) {
                anim_state         = BONGO_PREP;
                idle_timeout_timer = timer_read32();
            }
            break;

        default:
            break;
    }
}

// WPM and the clock, placed over parts of the art that are blank in every
// frame: the top left on the small screen, the whole top row on the large one.
static void draw_bongo_overlay(void) {
#    ifdef WPM_ENABLE
    char wpm_str[9];
    snprintf(wpm_str, sizeof(wpm_str), "WPM %03u", (unsigned)get_current_wpm());
    oled_set_cursor(0, 0);
    oled_write(wpm_str, false);
#    endif

#    ifdef SAT75_OLED_LARGE
    oled_set_cursor(14, 0);
#    else
    oled_set_cursor(0, 2);
#    endif
    oled_write(s75_get_time(), false);
}

void draw_bongo(bool minimal) {
    const char *frame;

    eval_anim_state();

    switch (anim_state) {
        case BONGO_TAP:
            frame             = BONGO_TAP_SET(minimal)[current_tap_frame];
            current_tap_frame = (current_tap_frame + 1) % BONGO_TAP_FRAMES;
            break;

        case BONGO_PREP:
            frame = BONGO_PREP_SET(minimal)[0];
            break;

        case BONGO_IDLE:
        default:
            frame = BONGO_IDLE_SET(minimal)[current_idle_frame];
            if (timer_elapsed32(anim_timer) > BONGO_FRAME_MS) {
                current_idle_frame = (current_idle_frame + 1) % BONGO_IDLE_FRAMES;
                anim_timer         = timer_read32();
            }
            break;
    }

    oled_set_cursor(0, 0);
    oled_write_raw_P(frame, BONGO_ANIM_SIZE);

    if (!minimal) {
        draw_bongo_overlay();
    }
}

